import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox'], defaultViewport: { width: 1280, height: 900 } });
const p = await b.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push('pageerror ' + e.message));
p.on('console', (m) => { if (m.type() === 'error') errs.push('console ' + m.text()); });
await p.goto('file://' + process.cwd() + '/docs/index.html');
const click = async (sel) => { await p.waitForSelector(sel); await p.click(sel); await new Promise((r) => setTimeout(r, 400)); };
await click('[data-act=demo]');
await new Promise((r) => setTimeout(r, 1500));
await p.screenshot({ path: '/tmp/s1.png' });
await click('[data-act=view][data-v=insights]'); await new Promise((r) => setTimeout(r, 600));
await p.screenshot({ path: '/tmp/s2.png' });
await click('[data-act=view][data-v=steps]');
await click('[data-act=view][data-v=timeline]'); await new Promise((r) => setTimeout(r, 1200));
await click('[data-act=play]'); await new Promise((r) => setTimeout(r, 2500));
await p.screenshot({ path: '/tmp/s3.png' });
await click('[data-act=zoom][data-z=in]');
await click('.mk');
console.log('detail', (await p.$eval('#detail', (e) => e.innerText)).slice(0, 80));
await click('[data-act=record]'); await new Promise((r) => setTimeout(r, 4000));
await p.screenshot({ path: '/tmp/s4.png' });
console.log('errors', errs);
await b.close();
